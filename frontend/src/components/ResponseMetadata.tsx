import { Database, KeyRound, Zap } from "lucide-react";
import type { ChatMetadata } from "../types/chat";

/**
 * Per-reply metadata exactly as returned by POST /chat, shown as one quiet line
 * under the answer. Each data-testid element contains only the raw value.
 */
export function ResponseMetadata({ metadata }: { metadata: ChatMetadata }) {
  const cached = metadata.resolution_source === "LLM_CACHE";
  const failedOver = !cached && metadata.fallback_attempts > 0;
  const dot = <span className="text-line-strong" aria-hidden>·</span>;

  return (
    <div className="flex flex-wrap items-center gap-x-2 gap-y-1 text-xs text-faint" aria-label="Response metadata">
      <span
        className={`inline-flex items-center gap-1 rounded-md px-1.5 py-0.5 font-semibold ${
          cached
            ? "bg-violet-100 text-violet-700 dark:bg-violet-400/15 dark:text-violet-300"
            : "bg-emerald-100 text-emerald-700 dark:bg-emerald-400/15 dark:text-emerald-300"
        }`}
        title={cached ? "Served from the LiteLLM response cache" : "Generated by a live model call"}
      >
        {cached ? <Database size={11} aria-hidden /> : <Zap size={11} aria-hidden />}
        <span data-testid="meta-source">{metadata.resolution_source}</span>
      </span>
      <span data-testid="meta-model" title="Model">
        {metadata.model}
      </span>
      {dot}
      <span data-testid="meta-latency" className="tabular-nums" title="Server-measured latency">
        {metadata.latency_ms} ms
      </span>
      {dot}
      <span title="Input / output tokens of this request only">
        <span data-testid="meta-input-tokens" className="tabular-nums">
          {metadata.input_tokens}
        </span>{" "}
        in /{" "}
        <span data-testid="meta-output-tokens" className="tabular-nums">
          {metadata.output_tokens}
        </span>{" "}
        out tokens
      </span>
      {dot}
      <span className="inline-flex items-center gap-1" title={cached ? "Cache hit: no key was used" : "Key from the pool that answered"}>
        <KeyRound size={11} aria-hidden />
        <span data-testid="meta-key-id">{metadata.key_id ?? "—"}</span>
      </span>
      <span className={failedOver ? "font-medium text-orange-600 dark:text-orange-400" : "hidden"} title="Keys that failed before this one answered">
        {dot} fallback <span data-testid="meta-fallback-attempts">{metadata.fallback_attempts}</span>
      </span>
    </div>
  );
}
