import { ArrowDownToLine, ArrowUpFromLine, Clock3, Cpu, Database, KeyRound, Shuffle, Zap } from "lucide-react";
import type { ReactNode } from "react";
import type { ChatMetadata } from "../types/chat";

function Chip({ icon, label, children, tone = "neutral", title }: {
  icon: ReactNode;
  label?: string;
  children: ReactNode;
  tone?: "neutral" | "live" | "cache" | "warn";
  title?: string;
}) {
  const tones = {
    neutral: "border-slate-200 bg-white text-slate-600 dark:border-ink-700 dark:bg-ink-850 dark:text-slate-300",
    live: "border-emerald-200 bg-emerald-50 text-emerald-700 dark:border-emerald-500/30 dark:bg-emerald-500/10 dark:text-emerald-300",
    cache: "border-amber-200 bg-amber-50 text-amber-700 dark:border-amber-400/30 dark:bg-amber-400/10 dark:text-amber-300",
    warn: "border-orange-200 bg-orange-50 text-orange-700 dark:border-orange-400/30 dark:bg-orange-400/10 dark:text-orange-300",
  };
  return (
    <span
      title={title}
      className={`inline-flex items-center gap-1.5 rounded-full border px-2.5 py-1 text-xs font-medium ${tones[tone]}`}
    >
      <span aria-hidden className="shrink-0 opacity-80">
        {icon}
      </span>
      {label && <span className="text-[11px] font-normal opacity-70">{label}</span>}
      {children}
    </span>
  );
}

/**
 * Per-reply metadata exactly as returned by POST /chat.
 * Every data-testid element contains only the raw value so automated checks
 * can read it directly (labels/icons sit outside those elements).
 */
export function ResponseMetadata({ metadata }: { metadata: ChatMetadata }) {
  const cached = metadata.resolution_source === "LLM_CACHE";
  const failedOver = !cached && metadata.fallback_attempts > 0;
  const iconSize = 13;

  return (
    <div className="mt-3 flex flex-wrap items-center gap-1.5" aria-label="Response metadata">
      <Chip
        tone={cached ? "cache" : "live"}
        icon={cached ? <Database size={iconSize} /> : <Zap size={iconSize} />}
        title={cached ? "Served from the LiteLLM response cache" : "Generated by a live model call"}
      >
        <span data-testid="meta-source" className="font-mono text-[11px] tracking-wide">
          {metadata.resolution_source}
        </span>
      </Chip>

      <Chip icon={<Cpu size={iconSize} />} title="Model that produced the reply">
        <span data-testid="meta-model" className="font-mono text-[11px]">
          {metadata.model}
        </span>
      </Chip>

      <Chip icon={<Clock3 size={iconSize} />} title="Server-measured latency">
        <span data-testid="meta-latency">{metadata.latency_ms} ms</span>
      </Chip>

      <Chip icon={<ArrowDownToLine size={iconSize} />} label="in" title="Input (prompt) tokens for this request">
        <span data-testid="meta-input-tokens">{metadata.input_tokens}</span>
      </Chip>

      <Chip icon={<ArrowUpFromLine size={iconSize} />} label="out" title="Output (completion) tokens for this reply">
        <span data-testid="meta-output-tokens">{metadata.output_tokens}</span>
      </Chip>

      <Chip icon={<KeyRound size={iconSize} />} label="key" title="Key from the pool that answered">
        <span data-testid="meta-key-id" className="font-mono text-[11px]">
          {metadata.key_id ?? "cached response"}
        </span>
      </Chip>

      <Chip
        tone={failedOver ? "warn" : "neutral"}
        icon={<Shuffle size={iconSize} />}
        label="fallbacks"
        title={failedOver ? `${metadata.fallback_attempts} key(s) failed before ${metadata.key_id} answered` : "No key failed for this reply"}
      >
        <span data-testid="meta-fallback-attempts">{metadata.fallback_attempts}</span>
      </Chip>

      {failedOver && (
        <span className="text-xs text-orange-600 dark:text-orange-300">
          Failed over to {metadata.key_id} after {metadata.fallback_attempts} failed key{metadata.fallback_attempts > 1 ? "s" : ""}
        </span>
      )}
    </div>
  );
}
